// เรียกใช้ฟังก์ชัน pageLoad เมื่อหน้าเว็บโหลดสมบูรณ์
window.onload = pageLoad;

function pageLoad() {
    // ผูกเหตุการณ์การส่งฟอร์ม (Submit) เข้ากับฟังก์ชัน validateForm
    const form = document.getElementById("myRegister");
    form.onsubmit = validateForm;
}

function validateForm(event) {
    // -------------------------------------------------------------------------
    // Step 1: ป้องกันการรีเฟรชหน้าเว็บ หรือส่งข้อมูลผ่าน URL เมื่อกด Submit
    // -------------------------------------------------------------------------
    if (event) {
        event.preventDefault();
    }

    // -------------------------------------------------------------------------
    // Step 2: ดึงข้อมูลจากองค์ประกอบต่างๆ ในฟอร์ม Register
    // -------------------------------------------------------------------------
    const errorMsg = document.getElementById("errormsg");
    const username = document.forms["myRegister"]["username"].value.trim();
    const passwords = document.forms["myRegister"]["password"];
    const password = passwords[0].value;
    const retypePassword = passwords[1].value;

    // -------------------------------------------------------------------------
    // Step 3: ตรวจสอบว่า Password ทั้ง 2 ช่องตรงกันหรือไม่
    // -------------------------------------------------------------------------
    if (password !== retypePassword) {
        // หากไม่ตรงกัน แสดงข้อความแจ้งเตือน และยกเลิกการลงทะเบียน
        errorMsg.innerHTML = "รหัสผ่านไม่ตรงกัน กรุณากรอกใหม่อีกครั้ง";
        return false;
    }

    // -------------------------------------------------------------------------
    // Step 4: เคลียร์ข้อความแจ้งเตือนเมื่อผ่านการตรวจสอบ
    // -------------------------------------------------------------------------
    errorMsg.innerHTML = "";

    // -------------------------------------------------------------------------
    // Step 5: บันทึกข้อมูล Username และ Password ลงใน localStorage
    // -------------------------------------------------------------------------
    localStorage.setItem("username", username);
    localStorage.setItem("password", password);

    alert("ลงทะเบียนสำเร็จ! กำลังไปที่หน้า Login");

    // -------------------------------------------------------------------------
    // Step 6: นำทางไปยังหน้า login.html
    // -------------------------------------------------------------------------
    window.location.href = "login.html";
    return true;
}